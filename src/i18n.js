export function makeT(lang) {
  const dict = STR[lang] || STR.ro;
  return (key, vars) => {
    let s = dict[key] ?? STR.ro[key] ?? key;
    if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
    return s;
  };
}